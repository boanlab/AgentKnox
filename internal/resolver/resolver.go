// resolveDebuginfod (T3) fetches separated symbols/DWARF for the binary's
// build-id from a debuginfod server, resolves the SSL boundary symbols in the
// fetched debug object, and converts their virtual addresses to file offsets in
// the ORIGINAL binary (same build-id ⇒ same load layout). Network is used only
// when DEBUGINFOD_URLS is set, so the resolver stays offline-safe by default.
func resolveDebuginfod(orig *elf.File, buildID string) (map[string]uint64, bool) {
	if buildID == "" {
		return nil, false
	}
	urls := os.Getenv("DEBUGINFOD_URLS")
	if urls == "" {
		return nil, false // no server configured: skip (offline default)
	}
	for _, base := range strings.Fields(urls) {
		debugPath, ok := fetchDebuginfod(base, buildID)
		if !ok {
			continue
		}
		df, err := elf.Open(debugPath)
		if err != nil {
			continue
		}
		vaddrs := symbolVaddrs(df)
		_ = df.Close()
		if len(vaddrs) == 0 {
			continue
		}
		out := map[string]uint64{}
		for k, va := range vaddrs {
			if off, ok := vaddrToFileOffset(orig, va); ok {
				out[k] = off
			}
		}
		if len(out) > 0 {
			return out, true
		}
	}
	return nil, false
}

// fetchDebuginfod downloads the debuginfo object for buildID from a debuginfod
// server into a local cache and returns the cached path.
func fetchDebuginfod(base, buildID string) (string, bool) {
	cacheDir := filepath.Join(os.TempDir(), "agentknox-debuginfod")
	if err := os.MkdirAll(cacheDir, 0o750); err != nil {
		return "", false
	}
	dst := filepath.Join(cacheDir, buildID+".debug")
	if fi, err := os.Stat(dst); err == nil && fi.Size() > 0 {
		return dst, true // cached
	}
	url := strings.TrimRight(base, "/") + "/buildid/" + buildID + "/debuginfo"
	client := &http.Client{Timeout: 15 * time.Second}
	// URL base is DEBUGINFOD_URLS (operator-configured, trusted); path is a hex
	// build-id. This is the intended debuginfod protocol fetch.
	resp, err := client.Get(url) // #nosec G704 -- operator-configured debuginfod server
	if err != nil {
		return "", false
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", false
	}
	tmp := dst + ".tmp"
	out, err := os.Create(tmp)
	if err != nil {
		return "", false
	}
	if _, err := io.Copy(out, resp.Body); err != nil {
		_ = out.Close()
		_ = os.Remove(tmp)
		return "", false
	}
	_ = out.Close()
	if err := os.Rename(tmp, dst); err != nil {
		return "", false
	}
	return dst, true
}

// symbolVaddrs returns the SSL boundary symbols' virtual addresses from a debug
// object's symbol tables (either table may carry them).
func symbolVaddrs(f *elf.File) map[string]uint64 {
	want := map[string]string{}
	for key, name := range sslSymbols {
		want[name] = key
	}
	out := map[string]uint64{}
	for _, symsFn := range []func() ([]elf.Symbol, error){f.Symbols, f.DynamicSymbols} {
		syms, err := symsFn()
		if err != nil {
			continue
		}
		for _, s := range syms {
			if key, ok := want[s.Name]; ok && s.Value != 0 {
				out[key] = s.Value
			}
		}
	}
	return out
}

// aeadSymbols maps a logical offset key to the aws-lc/aws-lc-rs AEAD boundary
// symbol. Rustls (Codex) has no stable SSL_read; the plaintext record is instead
// at EVP_AEAD_CTX_open (just-decrypted inbound) / EVP_AEAD_CTX_seal (about-to-
// encrypt outbound).
var aeadSymbols = map[string]string{
	keyAEADOpen: "EVP_AEAD_CTX_open",
	keyAEADSeal: "EVP_AEAD_CTX_seal",
}

// resolveAEADBoundary (T7) recovers the AEAD decrypt/encrypt boundary offsets for
// stacks without a stable SSL_read (rustls/aws-lc-rs, e.g. Codex) by looking up
// the AEAD symbols in both symbol tables. A fully stripped build falls through
// (names gone); a T4 offset-DB entry or T5 signature is then required.
func resolveAEADBoundary(f *elf.File) (map[string]uint64, bool) {
	want := map[string]string{}
	for key, name := range aeadSymbols {
		want[name] = key
	}
	out := map[string]uint64{}
	for _, symsFn := range []func() ([]elf.Symbol, error){f.DynamicSymbols, f.Symbols} {
		syms, err := symsFn()
		if err != nil {
			continue
		}
		for _, s := range syms {
			if key, ok := want[s.Name]; ok && s.Value != 0 {
				if off, ok := vaddrToFileOffset(f, s.Value); ok {
					out[key] = off
				}
			}
		}
	}
	if len(out) == 0 {
		return nil, false
	}
	return out, true
}
